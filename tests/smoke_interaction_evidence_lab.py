"""Exercise original concurrent search, modal/tabs, anchor, and dashboard in Chromium."""
import sys
from pathlib import Path
from playwright.sync_api import sync_playwright, expect
ROOT=Path(__file__).resolve().parents[1]
LAB=ROOT/"docs/references/ui-ux-research-sources/interaction-evidence-lab-2026-11-26.html"

def main(out):
    out.mkdir(parents=True,exist_ok=True)
    with sync_playwright() as p:
        browser=p.chromium.launch()
        for width in (1024,390):
            page=browser.new_page(viewport={"width":width,"height":844},reduced_motion="reduce")
            errors=[]
            page.on("pageerror",lambda err:errors.append(str(err)))
            page.goto(LAB.as_uri())
            status=page.locator("#search-status")
            page.get_by_role("button",name="Search",exact=True).click()
            expect(status).to_have_attribute("data-state","pending")
            page.screenshot(path=str(out/f"{width}-search-pending.png"),full_page=True)
            page.locator("#query").fill("history")
            page.get_by_role("button",name="Search",exact=True).click()
            expect(status).to_have_text("1 results for history")
            page.wait_for_timeout(850)
            expect(page.locator("#results li")).to_have_text(["History timelines"])
            page.locator("#query").fill("math")
            page.get_by_role("button",name="Search",exact=True).click()
            expect(page.locator("#results-region")).to_have_attribute("aria-busy","true")
            page.locator("#cancel-search").click()
            expect(status).to_have_attribute("data-state","cancelled")
            expect(page.locator("#query")).to_be_focused()
            page.wait_for_timeout(850)
            expect(page.locator("#results li")).to_have_text(["History timelines"])
            page.locator("#query").fill("science")
            page.locator("#fail-next").check()
            page.get_by_role("button",name="Search",exact=True).click()
            expect(status).to_have_attribute("data-state","error")
            expect(page.locator("#results li")).to_have_text(["History timelines"])
            page.locator("#retry-search").click()
            expect(page.locator("#results li")).to_have_text(["Science review"])
            page.locator("#open-detail").click()
            expect(page.get_by_role("dialog")).to_be_visible()
            expect(page.locator("#close-detail")).to_be_focused()
            page.screenshot(path=str(out/f"{width}-modal.png"),full_page=True)
            page.keyboard.press("Escape")
            expect(page.get_by_role("dialog")).not_to_be_visible()
            expect(page.locator("#open-detail")).to_be_focused()
            page.locator("#query").fill("absent")
            page.get_by_role("button",name="Search",exact=True).click()
            expect(status).to_have_attribute("data-state","empty")
            expect(page.locator("#results li")).to_have_count(0)
            page.locator("#search-tab").focus()
            page.keyboard.press("ArrowRight")
            expect(page.locator("#reader-tab")).to_be_focused()
            expect(page.locator("#search-tab")).to_have_attribute("aria-selected","true")
            page.keyboard.press("Enter")
            expect(page.locator("#reader-panel")).to_be_visible()
            expect(page.locator("#anchor-status")).to_have_attribute("data-state","matched")
            for revision,state in (("shifted","matched"),("ambiguous","ambiguous"),("missing","missing"),("context","review-required")):
                page.locator("#revision").select_option(revision)
                expect(page.locator("#anchor-status")).to_have_attribute("data-state",state)
                expect(page.locator("#document-text mark")).to_have_count(1 if state=="matched" else 0)
            page.screenshot(path=str(out/f"{width}-unresolved-anchor.png"),full_page=True)
            page.locator("#export-anchor").click()
            expect(page.locator("#anchor-json")).to_contain_text("TextQuoteSelector")
            page.locator("#dashboard-tab").click()
            expect(page.locator("#filter-status")).to_have_text("3 subjects; 11 correct of 15 attempts; 73% accuracy")
            page.locator("#subject").select_option("Math")
            expect(page.locator("#data-rows tr")).to_have_count(1)
            expect(page.locator("#filter-status")).to_have_text("1 subjects; 8 correct of 10 attempts; 80% accuracy")
            page.locator("#subject").select_option("Science")
            expect(page.locator("#data-rows")).to_contain_text("N/A")
            expect(page.locator("#bars meter")).to_have_count(0)
            page.locator("#subject").select_option("Language")
            expect(page.locator("#filter-status")).to_have_text("No matching subjects")
            page.locator("#clear-filter").click()
            expect(page.locator("#subject")).to_be_focused()
            expect(page.locator("#data-rows tr")).to_have_count(3)
            page.screenshot(path=str(out/f"{width}-dashboard.png"),full_page=True)
            assert page.evaluate("document.documentElement.scrollWidth <= innerWidth")
            assert not errors,errors
            page.close()
        browser.close()
    print("Interaction lab: real Chromium desktop/mobile search races, cancellation/retry, manual tabs, modal focus restoration, anchor ambiguity, data filters and missing denominator passed")

if __name__=="__main__":
    main(Path(sys.argv[1]))
